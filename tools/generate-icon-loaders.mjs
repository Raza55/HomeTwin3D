import { readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
const require = createRequire(import.meta.url);
const root = dirname(require.resolve('lucide-react/package.json'));
const index = await readFile(join(root, 'dist/esm/icons/index.js'), 'utf8');
const entries = [...index.matchAll(/export \{ default as (\w+) \} from '\.\/([^']+)';/g)];
if (entries.length < 100) throw new Error('Unexpected Lucide export format');
const source = `// Generated by tools/generate-icon-loaders.mjs; preserves every name in Lucide's icons registry.\nexport const iconLoaders = {\n${entries.map(([, name, file]) => `  ${JSON.stringify(name)}: () => import('lucide-react/dist/esm/icons/${file}'),`).join('\n')}\n};\n`;
const target = new URL('../src/services/iconLoaders.generated.ts', import.meta.url);
if (await readFile(target, 'utf8').catch(() => '') !== source) await writeFile(target, source);
console.log(`Lucide: ${entries.length} on-demand icons`);
